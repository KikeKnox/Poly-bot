const CLOB_V2_URL: &str = "https://clob.polymarket.com";

/// Timeout applied to each individual HTTP call to the CLOB.
///
/// The executor processes intents in a single sequential task, so there is no
/// concurrency of live orders to limit with a semaphore — this timeout is what
/// bounds how long the pipeline can hang on a slow call. 5 s covers
/// any normal Polymarket response.
const CLOB_HTTP_TIMEOUT: Duration = Duration::from_secs(5);

/// Shorter timeout for cancels. They are idempotent (with a single retry), and the
/// cancel path precedes urgent bail-sells (anti-dup, kill) — with 5 s the
/// worst case was 10.25 s of blocked executor; with 2 s it drops to 4.25 s.
const CLOB_CANCEL_TIMEOUT: Duration = Duration::from_secs(2);

/// Backoff of the single retry of idempotent operations.
const RETRY_BACKOFF: Duration = Duration::from_millis(250);

/// Single retry with backoff for **idempotent** CLOB operations
/// (cancel, GET queries). NEVER use with `post_order`/`post_orders`: they are not
/// idempotent — a timeout can mean "order accepted", and resending
/// would duplicate the purchase. That scenario is resolved by user_ws + the startup
/// reconciliation (`fetch_open_gtd_orders` + positions).
async fn retry_once<T, F, Fut>(op_name: &str, mut op: F) -> anyhow::Result<T>
where
    F: FnMut() -> Fut,
    Fut: std::future::Future<Output = anyhow::Result<T>>,
{
    match op().await {
        Ok(v) => Ok(v),
        Err(e1) => {
            tracing::warn!(
                "{op_name}: failed, single retry in {}ms: {e1}",
                RETRY_BACKOFF.as_millis()
            );
            tokio::time::sleep(RETRY_BACKOFF).await;
            op().await.map_err(|e2| {
                anyhow::anyhow!("{op_name}: retry failed: {e2} (first error: {e1})")
            })
        }
    }
}

pub type AuthedClient = Client<Authenticated<Normal>>;

pub struct AuthedClobClient {
    pub client: AuthedClient,
    pub signer: Arc<PrivateKeySigner>,
}

pub struct SubmitResult {
    pub order_id: String,
    pub executed_price: Option<Decimal>,
    pub executed_size: Option<Decimal>,
    /// `false` if the CLOB rejected the order (success:false in the HTTP response).
    /// Different from "FOK without fill" (success:true, making_amount=0).
    pub success: bool,
    pub error: Option<String>,
    /// UUIDs of the trades generated by this order (same IDs that arrive via user_ws MATCHED).
    /// Empty if the order did not fill immediately (GTD, FOK without counterparty).
    pub trade_ids: Vec<String>,
}

/// Writes or updates `POLY_API_KEY`, `POLY_API_SECRET` and `POLY_API_PASSPHRASE`
/// in the `.env` file of the job directory.
///
/// Only those three lines are touched; the rest of the file stays intact.
/// Commented lines (`# POLY_API_...`) are not modified.
/// If any of the three does not exist in the file, it is appended at the end.
fn persist_api_creds_to_dotenv(key: &str, secret: &str, passphrase: &str) -> anyhow::Result<()> {
    let path = std::path::Path::new(".env");
    let existing = std::fs::read_to_string(path).unwrap_or_default();

    let targets = [
        ("POLY_API_KEY", key),
        ("POLY_API_SECRET", secret),
        ("POLY_API_PASSPHRASE", passphrase),
    ];

    let mut lines: Vec<String> = existing.lines().map(String::from).collect();
    let mut written = [false; 3];

    for line in lines.iter_mut() {
        if line.trim_start().starts_with('#') {
            continue;
        }
        for (i, (var, val)) in targets.iter().enumerate() {
            if line.starts_with(&format!("{var}=")) {
                *line = format!("{var}={val}");
                written[i] = true;
                break;
            }
        }
    }

    for (i, (var, val)) in targets.iter().enumerate() {
        if !written[i] {
            lines.push(format!("{var}={val}"));
        }
    }

    let mut content = lines.join("\n");
    if !content.ends_with('\n') {
        content.push('\n');
    }

    // Credentials on disk: force 0o600 (owner only) before and during the write.
    // Atomic write: written to `.env.tmp` (same directory) and then
    // rename(2) is used, which on the same filesystem is atomic — if the process is killed midway,
    // `.env` stays intact and `.env.tmp` may be left orphaned (manually cleanable).
    {
        use std::io::Write as _;
        use std::os::unix::fs::{OpenOptionsExt as _, PermissionsExt as _};

        let tmp_path = std::path::Path::new(".env.tmp");

        // Write with 0o600 permissions to the temporary file.
        let mut f = std::fs::OpenOptions::new()
            .create(true)
            .write(true)
            .truncate(true)
            .mode(0o600)
            .open(tmp_path)?;
        f.write_all(content.as_bytes())?;
        // Make sure the bytes reach the kernel before the rename.
        f.flush()?;
        drop(f);

        // If the destination already exists, make sure it has 0o600 before the rename.
        if path.exists() {
            std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))?;
        }

        // Atomic rename: the destination .env is never left truncated midway through the write.
        if let Err(e) = std::fs::rename(tmp_path, path) {
            // Clean up the orphaned tmp before propagating the error.
            let _ = std::fs::remove_file(tmp_path);
            return Err(e.into());
        }
    }
    Ok(())
}

/// Authenticate to the CLOB and return an `AuthedClobClient` plus the `DerivedCreds`
/// needed by `user_ws` and the API state.
///
/// Credential priority: `.env` / environment → derive from the wallet via CLOB `/derive-api-key`.
/// In live mode, if the credentials were not in `.env`, they are derived and persisted
/// automatically to `.env` so the next startup does not need to derive again.
/// Credentials are NEVER stored in SQLite.
pub async fn bootstrap(config: &Config) -> anyhow::Result<(AuthedClobClient, DerivedCreds)> {
    let identity = config.resolve_wallet_identity()?;

    let signer: PrivateKeySigner = identity
        .private_key
        .trim()
        .parse()
        .map_err(|e| anyhow::anyhow!("invalid private key: {e}"))?;
    let signer = Arc::new(signer.with_chain_id(Some(POLYGON)));

    let eoa = format!("{}", signer.address());

    let sig_type = match identity.signature_type {
        0 => SignatureType::Eoa,
        1 => SignatureType::Proxy,
        2 => SignatureType::GnosisSafe,
        3 => SignatureType::Poly1271,
        n => anyhow::bail!("unsupported signature_type {n}"),
    };

    let unauth = Client::new(CLOB_V2_URL, ClobConfig::default())?;

    let mut auth_builder = unauth
        .authentication_builder(signer.as_ref())
        .signature_type(sig_type);

    if let Some(ref funder_hex) = identity.funder_address {
        if !funder_hex.is_empty() {
            let funder: alloy::primitives::Address = funder_hex
                .parse()
                .map_err(|e| anyhow::anyhow!("POLY_PROXY_ADDRESS invalid: {e}"))?;
            auth_builder = auth_builder.funder(funder);
        }
    }

    // Credential priority: `.env` / environment → derive from the wallet.
    let poly_api_key = std::env::var("POLY_API_KEY").ok().filter(|x| !x.is_empty());
    let poly_api_secret = std::env::var("POLY_API_SECRET")
        .ok()
        .filter(|x| !x.is_empty());
    let poly_api_passphrase = std::env::var("POLY_API_PASSPHRASE")
        .ok()
        .filter(|x| !x.is_empty());
    let creds_from_env = match (
        poly_api_key.as_deref(),
        poly_api_secret.as_deref(),
        poly_api_passphrase.as_deref(),
    ) {
        (Some(k), Some(s), Some(p)) => {
            let uuid: Uuid = k
                .parse()
                .map_err(|e| anyhow::anyhow!("POLY_API_KEY is not a valid UUID: {e}"))?;
            auth_builder =
                auth_builder.credentials(polymarket_client_sdk_v2::auth::Credentials::new(
                    uuid,
                    s.to_string(),
                    p.to_string(),
                ));
            tracing::info!(
                api_key_len = k.len(),
                source = "env",
                "bootstrap: credentials from .env"
            );
            true
        }
        _ => {
            tracing::warn!(%eoa, dry_run = config.mode != crate::types::Mode::Live,
                "bootstrap: CLOB credentials missing — deriving from the wallet");
            false
        }
    };

    let authed_client = auth_builder
        .authenticate()
        .await
        .map_err(|e| anyhow::anyhow!("CLOB authentication failed: {e}"))?;

    let cred = authed_client.credentials();
    let api_key = cred.key().to_string();
    let api_secret = cred.secret().expose_secret().to_string();
    let api_passphrase = cred.passphrase().expose_secret().to_string();

    // In live without previous credentials: persist to .env for the next startup.
    if !creds_from_env && config.mode == crate::types::Mode::Live {
        match persist_api_creds_to_dotenv(&api_key, &api_secret, &api_passphrase) {
            Ok(()) => tracing::info!(
                api_key_len = api_key.len(),
                "bootstrap: CLOB credentials derived and saved to .env"
            ),
            Err(e) => tracing::warn!(
                error = %e,
                "bootstrap: credentials derived OK but could not write .env — \
                 copy them manually from the logs for the next startup"
            ),
        }
    }

    let derived = DerivedCreds {
        eoa_address: eoa,
        funder_address: identity.funder_address.clone(),
        api_key,
        api_secret,
        api_passphrase,
    };

    // Ask the Polymarket backend to enable/refresh the CTF Exchange allowance
    // over the pUSD collateral. Done ONCE at startup so as not to saturate the API.
    // The on-chain approval is asynchronous — the equity reconciler will see the change
    // on the next tick (60 s) once the tx is mined on Polygon.
    let allowance_req = BalanceAllowanceRequest::builder()
        .asset_type(AssetType::Collateral)
        .build();
    match authed_client.update_balance_allowance(allowance_req).await {
        Ok(()) => tracing::info!("bootstrap: pUSD allowance request sent to the CLOB"),
        Err(e) => {
            tracing::warn!(error = %e, "bootstrap: update_balance_allowance failed (non-critical)")
        }
    }

    Ok((
        AuthedClobClient {
            client: authed_client,
            signer,
        },
        derived,
    ))
}

/// Rounds `price` UP to the `tick` scale — symmetric to
/// `truncate_to_tick` (types.rs) but for the Sell side. Truncating an ask downwards
/// (e.g. 0.617 with tick 0.01 → 0.61 instead of 0.62) gives away up to 1 tick/share on
/// every sell, systematically against the bot.
fn ceil_to_tick(price: Decimal, tick: Decimal) -> Decimal {
    let truncated = crate::types::truncate_to_tick(price, tick);
    if truncated == price {
        truncated
    } else {
        truncated + tick
    }
}

/// Adjusts `price` to the `tick` scale and clamps it to the valid range `[tick, 1 - tick]`.
///
/// The direction of the adjustment depends on the order side. On a Buy we never
/// want to overpay → we truncate DOWN (also because `round_dp` could raise
/// the price above 1-tick). On a Sell, truncating down gives price away to the
/// buyer → we round UP (`ceil_to_tick`). `Side::Unknown` (`#[serde(other)]`
/// variant of the SDK, should not reach here in practice) is treated as
/// Buy as it is the previous conservative behavior.
fn adjust_to_tick(price: Decimal, tick: Decimal, side: Side) -> Decimal {
    // TICK-1: the truncation itself lives in types.rs to share it with the price-zone
    // fallback when the tick_size query fails.
    let adjusted = match side {
        Side::Sell => ceil_to_tick(price, tick),
        _ => crate::types::truncate_to_tick(price, tick),
    };
    let min = tick;
    let max = (Decimal::ONE - tick).trunc_with_scale(tick.scale());
    adjusted.clamp(min, max)
}

/// TTL to force a periodic refresh of the SDK's internal caches
/// (tick_size, neg_risk, fee_rate…). The SDK caches them in a `DashMap` without TTL
/// and without per-token invalidation; the selective refresh below only detects
/// ONE direction of tick change (cache coarser than what the price asks for).
/// The inverse scenario (the market raises the tick, e.g. from 0.001 to 0.01 when crossing 0.96)
/// triggers nothing because there is no way to detect it just by looking at `price.scale()`.
/// Instead of trying to cover that direction with more heuristics, we force a
/// global refresh every `TICK_CACHE_TTL` — it bounds the worst-case staleness to that
/// interval regardless of the direction of the change.
const TICK_CACHE_TTL: Duration = Duration::from_secs(5);
static LAST_CACHE_INVALIDATION: std::sync::atomic::AtomicI64 = std::sync::atomic::AtomicI64::new(0);

/// Pure so the expiry criterion can be tested without depending on a real clock.
fn tick_cache_expired(last_invalidation: i64, now: i64, ttl: Duration) -> bool {
    now - last_invalidation >= ttl.as_secs() as i64
}

/// Invalidates the SDK's internal caches if `TICK_CACHE_TTL` has passed since the last time.
/// CAS so concurrent calls do not trigger redundant invalidations.
fn maybe_invalidate_tick_cache(bundle: &AuthedClobClient) {
    let now = Utc::now().timestamp();
    let last = LAST_CACHE_INVALIDATION.load(std::sync::atomic::Ordering::Relaxed);
    if tick_cache_expired(last, now, TICK_CACHE_TTL)
        && LAST_CACHE_INVALIDATION
            .compare_exchange(
                last,
                now,
                std::sync::atomic::Ordering::Relaxed,
                std::sync::atomic::Ordering::Relaxed,
            )
            .is_ok()
    {
        bundle.client.invalidate_internal_caches();
    }
}

/// Same direction criterion as `adjust_to_tick`, applied to the price-zone
/// fallback (TICK-1) when the `tick_size` query fails.
fn fallback_tick_price(price: Decimal, side: Side) -> Decimal {
    let tick = crate::types::tick_from_price(price);
    match side {
        Side::Sell => ceil_to_tick(price, tick),
        _ => crate::types::truncate_to_tick(price, tick),
    }
}

/// Resolves the market tick and adjusts `price` to it.
///
/// Polymarket lowers the tick from 0.01 to 0.001 when the book crosses 0.96 (WS event
/// `tick_size_change`). The SDK caches tick sizes in a `DashMap` without TTL and does not listen to
/// that event, so a tick cached as 0.01 can go stale right when the
/// market has already moved to 0.001 — silently degrading a 3-decimal price.
async fn price_at_market_tick(
    bundle: &AuthedClobClient,
    sdk_token_id: SdkU256,
    price: Decimal,
    side: Side,
) -> anyhow::Result<Decimal> {
    // Force a periodic cache refresh (see TICK_CACHE_TTL) to
    // bound the staleness in the direction that the scale check below does not cover.
    maybe_invalidate_tick_cache(bundle);

    let tick_resp = match bundle.client.tick_size(sdk_token_id).await {
        Ok(resp) => resp,
        Err(e) => {
            // TICK-1: fallback derived from the price zone — truncating to 2 decimals
            // used to mangle 0.999 → 0.99.
            tracing::warn!(
                token_id = %sdk_token_id,
                error = %e,
                "clob: tick_size query failed — using tick derived from the price zone"
            );
            return Ok(fallback_tick_price(price, side));
        }
    };
    let mut tick = tick_resp.minimum_tick_size.as_decimal();

    // Selective refresh: if the cached tick has fewer decimals than the price
    // asks for (e.g. tick=0.01 but we want 0.999), the cache may be stale due to
    // a recent tick_size_change. It is invalidated and re-queried ONLY ONCE. Zero cost
    // in the normal scenario (tick already allows the requested scale).
    if price.scale() > tick.scale() {
        bundle.client.invalidate_internal_caches();
        match bundle.client.tick_size(sdk_token_id).await {
            Ok(resp) => tick = resp.minimum_tick_size.as_decimal(),
            Err(e) => {
                // TICK-1: fallback derived from the price zone — truncating to 2 decimals
                // used to mangle 0.999 → 0.99.
                tracing::warn!(
                    token_id = %sdk_token_id,
                    error = %e,
                    "clob: tick_size re-query after cache invalidation failed — using tick derived from the price zone"
                );
                return Ok(fallback_tick_price(price, side));
            }
        }
    }

    let adjusted = adjust_to_tick(price, tick, side);
    if price != adjusted {
        tracing::info!(
            token_id = %sdk_token_id,
            requested_price = %price,
            tick = %tick,
            price_final = %adjusted,
            "clob: price adjusted to the market's real tick"
        );
    }
    Ok(adjusted)
}

/// Builds and signs a **buy** order without sending it.
///
/// - If `intent.limit_price` is `Some(px)`: **limit** order (limit_order + size) with `px`
///   as the maximum price. The order is killed (FOK/FAK) if the fill would require exceeding that price.
///   This prevents "out-of-price" buys when the book moves relative to the snapshot.
/// - If `intent.limit_price` is `None`: **market** order by USDC amount (previous
///   behavior, used by non-arbitrage strategies).
///
/// Factored out to share it between `submit_market_buy` and `submit_sell`.
async fn build_signed_market_buy(
    bundle: &AuthedClobClient,
    intent: &OrderIntent,
    order_type: OrderType,
) -> anyhow::Result<SignedOrder> {
    let token_id = SdkU256::from_str_radix(&intent.token_id, 10)
        .or_else(|_| SdkU256::from_str_radix(intent.token_id.trim_start_matches("0x"), 16))
        .map_err(|_| anyhow::anyhow!("invalid token_id: {:?}", intent.token_id))?;

    let signable = if let Some(lp_raw) = intent.limit_price {
        // Limit order — the price ceiling guarantees Up + Down < 1 under slippage.
        // The CLOB kills the order (FOK/FAK) if there is no liquidity at price ≤ lp.
        // PCS-2: adjust to the market's REAL tick before building the order —
        // the SDK does not truncate (it aborts the build if price.scale() > tick.scale()).
        let lp = price_at_market_tick(bundle, token_id, lp_raw, Side::Buy).await?;
        // Truncate to whole shares: whole × price(≤4dp) → ≤4dp USDC (maker_amount), within
        // the margin the tick allows — with tick 0.001 the SDK accepts up to 4dp.
        let size_trunc = intent.size.trunc_with_scale(0);
        if size_trunc <= Decimal::ZERO {
            anyhow::bail!(
                "build_signed_market_buy (limit): size after truncating to whole is 0 \
                 (price={}, size={}, limit={})",
                intent.price,
                intent.size,
                lp
            );
        }
        // Polymarket minimum for a marketable BUY = $1 USDC.
        let maker_usdc = lp * size_trunc;
        if maker_usdc < Decimal::ONE {
            anyhow::bail!(
                "build_signed_market_buy (limit): makerAmount ${maker_usdc} < $1 minimum \
                 (price={lp}, size={size_trunc})"
            );
        }
        tokio::time::timeout(
            CLOB_HTTP_TIMEOUT,
            bundle
                .client
                .limit_order()
                .token_id(token_id)
                .price(lp)
                .size(size_trunc)
                .side(Side::Buy)
                .order_type(order_type.clone())
                .build(),
        )
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "build limit order ({order_type:?}): timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| anyhow::anyhow!("build limit order ({order_type:?}): {e}"))?
    } else {
        // Market order by USDC amount (non-arb strategies without a price ceiling).
        // The CLOB API requires the maker amount to have at most 2 decimals.
        // We truncate (not round) so as not to exceed the amount reserved by the risk accounting.
        let raw_usdc = (intent.price * intent.size).trunc_with_scale(2);
        if raw_usdc <= Decimal::ZERO {
            anyhow::bail!(
                "build_signed_market_buy (market): USDC amount after truncating to 2 decimals is 0 \
                 (price={}, size={})",
                intent.price,
                intent.size
            );
        }
        let usdc_amount =
            Amount::usdc(raw_usdc).map_err(|e| anyhow::anyhow!("Amount::usdc: {e}"))?;
        tokio::time::timeout(
            CLOB_HTTP_TIMEOUT,
            bundle
                .client
                .market_order()
                .token_id(token_id)
                .amount(usdc_amount)
                .side(Side::Buy)
                .order_type(order_type.clone())
                .build(),
        )
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "build market order ({order_type:?}): timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| anyhow::anyhow!("build market order ({order_type:?}): {e}"))?
    };

    bundle
        .client
        .sign(bundle.signer.as_ref(), signable)
        .await
        .map_err(|e| anyhow::anyhow!("sign order ({order_type:?}): {e}"))
}

/// Maps a buy `PostOrderResponse` to `SubmitResult`.
///
/// Factored out to share it between `submit_market_buy` and `submit_orders_batch`.
/// - `making_amount` = pUSD spent; `taking_amount` = shares received.
fn map_buy_response(
    resp: PostOrderResponse,
    intent: &OrderIntent,
    order_type: &OrderType,
) -> SubmitResult {
    if !resp.success {
        tracing::warn!(
            order_id = %resp.order_id,
            error    = ?resp.error_msg,
            market   = %intent.market_cid,
            ?order_type,
            "clob: order rejected by the CLOB"
        );
        return SubmitResult {
            order_id: resp.order_id,
            executed_price: None,
            executed_size: None,
            success: false,
            error: resp.error_msg,
            trade_ids: vec![],
        };
    }
    let (executed_price, executed_size) =
        if resp.making_amount > Decimal::ZERO && resp.taking_amount > Decimal::ZERO {
            (
                Some(resp.making_amount / resp.taking_amount),
                Some(resp.taking_amount),
            )
        } else {
            tracing::info!(
                order_id = %resp.order_id,
                status   = %resp.status,
                market   = %intent.market_cid,
                ?order_type,
                "clob: order without fill (unmatched or FOK without counterparty)"
            );
            (None, None)
        };
    SubmitResult {
        order_id: resp.order_id,
        executed_price,
        executed_size,
        success: true,
        error: None,
        trade_ids: resp.trade_ids,
    }
}

/// Shared core for **market buy** orders (Buy + Amount::usdc).
///
/// Both legs of the hedge are always buys: the scarce leg uses FOK, the abundant one FAK.
/// Sells of the orphan leg use `submit_sell` (Side::Sell + Amount::shares).
///
/// **No retry on purpose**: `post_order` is NOT idempotent — a
/// timeout can mean the CLOB accepted the order, and resending it would duplicate
/// the purchase. A failure here is reconciled by user_ws (the fill arrives anyway)
/// and by the startup reconciliation.
async fn submit_market_buy(
    bundle: &AuthedClobClient,
    intent: &OrderIntent,
    order_type: OrderType,
) -> anyhow::Result<SubmitResult> {
    let signed = build_signed_market_buy(bundle, intent, order_type.clone()).await?;

    let resp = tokio::time::timeout(CLOB_HTTP_TIMEOUT, bundle.client.post_order(signed))
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "post_order ({order_type:?}): timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| anyhow::anyhow!("post_order ({order_type:?}): {e}"))?;

    Ok(map_buy_response(resp, intent, &order_type))
}

/// Sends the **scarce** leg of a hedge as an FOK order (total Fill-or-Kill).
/// If it does not fill completely, the order is killed and `executed_size` is `None`.
pub async fn submit_order(
    bundle: &AuthedClobClient,
    intent: &OrderIntent,
) -> anyhow::Result<SubmitResult> {
    submit_market_buy(bundle, intent, OrderType::FOK).await
}

/// Sends YES + NO as a pair in a single `post_orders`.
///
/// A single HTTP request; the CLOB evaluates them against the same book state.
pub async fn submit_order_pair(
    bundle: &AuthedClobClient,
    yes_intent: &OrderIntent,
    no_intent: &OrderIntent,
) -> anyhow::Result<(SubmitResult, SubmitResult)> {
    // Sign in parallel: build+sign are purely local (resolve_version caches after
    // the first request). Sequencing them costs nothing and would lose ~200-500 µs.
    let (yes_signed, no_signed) = tokio::try_join!(
        build_signed_market_buy(bundle, yes_intent, OrderType::FOK),
        build_signed_market_buy(bundle, no_intent, OrderType::FOK),
    )?;

    let mut resps = tokio::time::timeout(
        CLOB_HTTP_TIMEOUT,
        bundle.client.post_orders(vec![yes_signed, no_signed]),
    )
    .await
    .map_err(|_| {
        anyhow::anyhow!(
            "submit_order_pair: timeout ({}s)",
            CLOB_HTTP_TIMEOUT.as_secs()
        )
    })?
    .map_err(|e| anyhow::anyhow!("submit_order_pair: {e}"))?;

    if resps.len() < 2 {
        anyhow::bail!(
            "submit_order_pair: incomplete response ({} of 2)",
            resps.len()
        );
    }
    let no_resp = resps.remove(1);
    let yes_resp = resps.remove(0);
    let yes_sr = map_buy_response(yes_resp, yes_intent, &OrderType::FOK);
    let no_sr = map_buy_response(no_resp, no_intent, &OrderType::FOK);
    // LIVE-4: pair result on ONE line — in the pilot
    // completeness was 0/5 and the log did not show WHY the other leg failed
    // (CLOB rejection vs FOK without fill) without correlating scattered warns.
    tracing::info!(
        cid          = %yes_intent.market_cid,
        yes_ok       = yes_sr.success,
        yes_filled   = ?yes_sr.executed_size,
        yes_error    = ?yes_sr.error,
        no_ok        = no_sr.success,
        no_filled    = ?no_sr.executed_size,
        no_error     = ?no_sr.error,
        yes_limit    = %yes_intent.price,
        no_limit     = %no_intent.price,
        "clob: result of the YES+NO pair"
    );
    Ok((yes_sr, no_sr))
}

