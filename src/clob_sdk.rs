/// An active GTD order returned by the CLOB during startup reconciliation.
pub struct GtdOrder {
    pub order_id: String,
    pub market_cid: String, // hex "0x..." of the condition_id
    pub token_id: String,   // decimal of the asset_id
    /// Side reported by the venue. `Side::Unknown` stays
    /// undetermined — consumers must not invent BUY.
    pub side: Side,
    pub price: Decimal,
    pub remaining: Decimal, // original_size − size_matched
    pub clear_at: i64,      // expiration unix timestamp
}

/// Queries all open GTD orders on the CLOB for this account.
/// Returns only those with status=Live and order_type=GTD with remaining shares > 0.
pub async fn fetch_open_gtd_orders(bundle: &AuthedClobClient) -> anyhow::Result<Vec<GtdOrder>> {
    // Pure query → safe to retry; the whole pagination is repeated from scratch.
    retry_once("fetch_open_gtd_orders", move || {
        fetch_open_gtd_orders_once(bundle)
    })
    .await
}

async fn fetch_open_gtd_orders_once(bundle: &AuthedClobClient) -> anyhow::Result<Vec<GtdOrder>> {
    let mut result = Vec::new();
    let mut cursor: Option<String> = None;
    loop {
        let req = OrdersRequest::builder().build();
        let page = tokio::time::timeout(
            CLOB_HTTP_TIMEOUT,
            bundle.client.orders(&req, cursor.clone()),
        )
        .await
        .map_err(|_| anyhow::anyhow!("fetch_open_gtd_orders: timeout"))?
        .map_err(|e| anyhow::anyhow!("fetch_open_gtd_orders: {e}"))?;

        // Iteration by value: allows moving `order.side` without requiring `Copy`
        // of the SDK type. The remaining fields are read the same way.
        for order in page.data {
            if order.status != OrderStatusType::Live {
                continue;
            }
            if order.order_type != SdkOrderType::GTD {
                continue;
            }
            let remaining = order.original_size - order.size_matched;
            if remaining <= Decimal::ZERO {
                continue;
            }
            result.push(GtdOrder {
                order_id: order.id.clone(),
                market_cid: order.market.to_string(),
                token_id: order.asset_id.to_string(),
                side: order.side,
                price: order.price,
                remaining,
                clear_at: order.expiration.timestamp(),
            });
        }

        // "LTE=" is the end cursor returned by the Polymarket API.
        let next = &page.next_cursor;
        if next.is_empty() || next == "LTE=" || page.count < page.limit {
            break;
        }
        cursor = Some(next.clone());
    }
    Ok(result)
}

/// Normalized state of an order queried by id — reconciliation of
/// `unknown_attempts` (POST with a lost response). It is the exchange's truth
/// about what happened to the order.
#[derive(Debug, Clone, PartialEq)]
pub enum ClobOrderStatus {
    /// Still alive in the book. `remaining` = unexecuted shares
    /// (`original_size − size_matched`).
    Live { remaining: Decimal },
    /// No longer in the book. `matched` = total executed shares;
    /// 0 if it was cancelled/expired without executing anything.
    Gone { matched: Decimal },
    /// The exchange does not know the order (HTTP 404): the POST never
    /// got it accepted — definitive outcome.
    NotFound,
}

/// Unknown reconciliation: queries `data/order/{id}`
/// and normalizes the response. `Err` = the query did NOT resolve (timeout, 5xx,
/// unknown status) — the caller must keep the attempt pending,
/// never release the claim on an `Err`.
pub async fn fetch_order_status(
    bundle: &AuthedClobClient,
    order_id: &str,
) -> anyhow::Result<ClobOrderStatus> {
    // A single call: `retry_once` would wrap the final error in anyhow and
    // destroy the chain — the 404 (key for `NotFound`) must be
    // classified over the SDK's raw error.
    let order = match tokio::time::timeout(CLOB_HTTP_TIMEOUT, bundle.client.order(order_id)).await {
        Err(_) => return Err(anyhow::anyhow!("fetch_order_status: timeout")),
        Ok(Err(e)) => {
            // 404 = the order does not exist on the exchange → the POST never arrived.
            if let Some(status) = e.downcast_ref::<polymarket_client_sdk_v2::error::Status>() {
                if status.status_code == polymarket_client_sdk_v2::error::StatusCode::NOT_FOUND {
                    return Ok(ClobOrderStatus::NotFound);
                }
            }
            return Err(anyhow::anyhow!("fetch_order_status: {e}"));
        }
        Ok(Ok(order)) => order,
    };

    let remaining = order.original_size - order.size_matched;
    match order.status {
        // Delayed = accepted but not yet inserted in the book
        // (market not active yet): still "alive" for claim purposes.
        OrderStatusType::Live | OrderStatusType::Delayed => Ok(ClobOrderStatus::Live { remaining }),
        OrderStatusType::Matched | OrderStatusType::Canceled | OrderStatusType::Unmatched => {
            Ok(ClobOrderStatus::Gone {
                matched: order.size_matched,
            })
        }
        // New API status that we do not know → undetermined.
        OrderStatusType::Unknown(raw) => Err(anyhow::anyhow!(
            "fetch_order_status: unknown status '{raw}'"
        )),
        // non_exhaustive: any future variant is undetermined.
        _ => Err(anyhow::anyhow!("fetch_order_status: unmappable variant")),
    }
}

/// A trade executed returned by the CLOB, already normalized to the bot's
