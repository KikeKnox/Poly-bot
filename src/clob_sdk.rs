/// Bot trades after `after_ts` (unix seconds).
/// `own_address` (EOA or proxy depending on wallet_mode) identifies our maker legs.
pub async fn fetch_trades_since(
    bundle: &AuthedClobClient,
    after_ts: i64,
    own_address: &str,
) -> anyhow::Result<Vec<ExecutedTrade>> {
    retry_once("fetch_trades_since", move || {
        fetch_trades_since_once(bundle, after_ts, own_address)
    })
    .await
}

/// Groups our maker fills by exact `(order_id, price)`, summing
/// `matched_amount` within each group. Pure so the grouping can be tested
/// without building fixtures of the SDK types (`MakerOrder` is `#[non_exhaustive]`).
/// Returns `(order_id, price, size_total)` per group, in order of first appearance.
fn group_own_maker_fills(ours: &[(&str, Decimal, Decimal)]) -> Vec<(String, Decimal, Decimal)> {
    let mut groups: Vec<(String, Decimal, Decimal)> = Vec::new();
    for &(order_id, price, amount) in ours {
        if let Some(g) = groups.iter_mut().find(|g| g.0 == order_id && g.1 == price) {
            g.2 += amount;
        } else {
            groups.push((order_id.to_string(), price, amount));
        }
    }
    groups
}

async fn fetch_trades_since_once(
    bundle: &AuthedClobClient,
    after_ts: i64,
    own_address: &str,
) -> anyhow::Result<Vec<ExecutedTrade>> {
    let own_lower = own_address.to_ascii_lowercase();
    let mut result = Vec::new();
    let mut cursor: Option<String> = None;
    loop {
        let req = TradesRequest::builder().after(after_ts).build();
        let page = tokio::time::timeout(
            CLOB_HTTP_TIMEOUT,
            bundle.client.trades(&req, cursor.clone()),
        )
        .await
        .map_err(|_| anyhow::anyhow!("fetch_trades_since: timeout"))?
        .map_err(|e| anyhow::anyhow!("fetch_trades_since: {e}"))?;

        for t in &page.data {
            if matches!(t.status, TradeStatusType::Failed) {
                continue;
            }
            match t.trader_side {
                TraderSide::Taker => {
                    // Our side = the trade's side (the taker defines the side).
                    result.push(ExecutedTrade {
                        exec_id: t.id.clone(), // taker: a single leg per trade
                        trade_id: t.id.clone(),
                        market_cid: t.market.to_string(),
                        token_id: t.asset_id.to_string(),
                        is_buy: matches!(t.side, Side::Buy),
                        price: t.price,
                        size: t.size,
                        match_ts: t.match_time.timestamp(),
                        own_order_id: Some(t.taker_order_id.clone()),
                    });
                }
                _ => {
                    // Maker: our legs are in maker_orders — side/price/size
                    // of OUR order, not of the trade (which carries the taker's side).
                    let ours: Vec<_> = t
                        .maker_orders
                        .iter()
                        .filter(|m| m.maker_address.to_string().eq_ignore_ascii_case(&own_lower))
                        .collect();
                    if ours.is_empty() {
                        continue;
                    }

                    // If several of OUR maker orders at different prices
                    // match in the same trade, before they were collapsed into a single
                    // ExecutedTrade at the price of the first (`ours[0]`) — PnL and
                    // strategy attribution (via gtd_orders) potentially wrong.
                    // We group by exact (order_id, price) and emit one
                    // ExecutedTrade per distinct group.
                    let keys: Vec<(&str, Decimal, Decimal)> = ours
                        .iter()
                        .map(|m| (m.order_id.as_str(), m.price, m.matched_amount))
                        .collect();
                    for (order_id, price, size) in group_own_maker_fills(&keys) {
                        if size <= Decimal::ZERO {
                            continue;
                        }
                        // Group representative (same order_id+price → same asset_id/side).
                        let Some(repr) = ours
                            .iter()
                            .find(|m| m.order_id == order_id && m.price == price)
                        else {
                            continue;
                        };
                        result.push(ExecutedTrade {
                            exec_id: maker_exec_id(&t.id, &order_id),
                            trade_id: t.id.clone(),
                            market_cid: t.market.to_string(),
                            token_id: repr.asset_id.to_string(),
                            is_buy: matches!(repr.side, Side::Buy),
                            price,
                            size,
                            match_ts: t.match_time.timestamp(),
                            own_order_id: Some(order_id),
                        });
                    }
                }
            }
        }

        let next = &page.next_cursor;
        if next.is_empty() || next == "LTE=" || page.count < page.limit {
            break;
        }
        cursor = Some(next.clone());
    }
    Ok(result)
}

/// Queries the account's USDC balance (pUSD collateral) on the CLOB.
pub async fn fetch_balance(bundle: &AuthedClobClient) -> anyhow::Result<Decimal> {
    retry_once("fetch_balance", move || async move {
        let req = BalanceAllowanceRequest::builder()
            .asset_type(AssetType::Collateral)
            .build();
        let resp = tokio::time::timeout(CLOB_HTTP_TIMEOUT, bundle.client.balance_allowance(req))
            .await
            .map_err(|_| anyhow::anyhow!("fetch_balance: timeout"))?
            .map_err(|e| anyhow::anyhow!("fetch_balance: {e}"))?;
        // The API returns the balance in atomic pUSD units (6 decimals on Polygon).
        Ok(resp.balance / rust_decimal_macros::dec!(1_000_000))
    })
    .await
}

