/// Sells `shares` of the token `token_id` at market price (best bid) as FAK.
///
/// Used by the orphan-leg manager and by near_certain to cut exposure
/// when a downtrend is detected or the position enters the target's risk band.
/// The SDK computes the execution price by querying the book (the token's bids) and truncates it
/// to the market tick_size (0.1 / 0.01 / 0.001 / 0.0001 → 1-4 decimals), so
/// the executed price can have up to 4 decimals depending on the market.
pub async fn submit_sell(
    bundle: &AuthedClobClient,
    token_id: &str,
    shares: Decimal,
) -> anyhow::Result<SubmitResult> {
    let sdk_token_id = SdkU256::from_str_radix(token_id, 10)
        .or_else(|_| SdkU256::from_str_radix(token_id.trim_start_matches("0x"), 16))
        .map_err(|_| anyhow::anyhow!("submit_sell: invalid token_id: {:?}", token_id))?;

    // Amount::shares accepts at most 2 decimals.
    // Truncate (not round) so as not to try to sell more shares than are held.
    // round_dp could increase the value (e.g. 10.005 → 10.01) and cause a CLOB rejection.
    let shares_rounded = shares.trunc_with_scale(2);
    if shares_rounded <= Decimal::ZERO {
        anyhow::bail!("submit_sell: shares after truncating to 2dp is 0 ({shares})");
    }
    let shares_amount =
        Amount::shares(shares_rounded).map_err(|e| anyhow::anyhow!("Amount::shares: {e}"))?;

    // market_order Sell + FAK: the SDK computes the price from the bids and executes
    // whatever it finds. We use FAK (not FOK) so that if the bid has less liquidity
    // than `shares`, it sells what it can in this cycle and retries in the next one.
    // The SDK truncates the price to the market tick_size internally (build() calls
    // client.tick_size(token_id) with an internal cache).
    let signable = tokio::time::timeout(
        CLOB_HTTP_TIMEOUT,
        bundle
            .client
            .market_order()
            .token_id(sdk_token_id)
            .amount(shares_amount)
            .side(Side::Sell)
            .order_type(OrderType::FAK)
            .build(),
    )
    .await
    .map_err(|_| {
        anyhow::anyhow!(
            "submit_sell build: timeout ({}s)",
            CLOB_HTTP_TIMEOUT.as_secs()
        )
    })?
    .map_err(|e| anyhow::anyhow!("submit_sell build: {e}"))?;

    // Log the effective tick_size to observe the price decimals.
    // tick_size() reads from the internal cache (populated by build() above → no extra HTTP).
    if let Ok(tick_resp) = bundle.client.tick_size(sdk_token_id).await {
        tracing::debug!(
            token_id = %token_id,
            tick_size = %tick_resp.minimum_tick_size,
            "submit_sell: market tick_size"
        );
    }

    let signed = bundle
        .client
        .sign(bundle.signer.as_ref(), signable)
        .await
        .map_err(|e| anyhow::anyhow!("submit_sell sign: {e}"))?;

    let resp = tokio::time::timeout(CLOB_HTTP_TIMEOUT, bundle.client.post_order(signed))
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "submit_sell post_order: timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| anyhow::anyhow!("submit_sell post_order: {e}"))?;

    // taking_amount = USDC received; making_amount = shares sold.
    let (executed_price, executed_size) =
        if resp.making_amount > Decimal::ZERO && resp.taking_amount > Decimal::ZERO {
            // For a sell: price = USDC / shares = taking / making
            (
                Some(resp.taking_amount / resp.making_amount),
                Some(resp.making_amount),
            )
        } else {
            (None, None)
        };

    Ok(SubmitResult {
        order_id: resp.order_id,
        executed_price,
        executed_size,
        success: resp.success,
        error: resp.error_msg,
        trade_ids: resp.trade_ids,
    })
}

/// Places a passive (maker) buy limit order with GTD expiry at `expiration`.
///
/// Used by `near_certain` in passive mode: instead of crossing the ask, the order rests
/// in the book at `price` (a price below the current ask) until a seller crosses it
/// or until `expiration` (typically the bracket's `clear_at`) expires it automatically.
///
/// The SDK validates that `price` is a multiple of the tick and lies in `[tick, 1-tick]` — it does not truncate,
/// it aborts the build otherwise. That is why `price` is adjusted internally to the real tick of the
/// market (`price_at_market_tick`) before building the order; the caller does not
/// need to truncate it.
/// `size` is truncated to whole shares (see the comment below about amount decimals).
pub async fn submit_limit_buy(
    bundle: &AuthedClobClient,
    token_id: &str,
    price: Decimal,
    size: Decimal,
    expiration: DateTime<Utc>,
    post_only: bool,
) -> anyhow::Result<SubmitResult> {
    let sdk_token_id = SdkU256::from_str_radix(token_id, 10)
        .or_else(|_| SdkU256::from_str_radix(token_id.trim_start_matches("0x"), 16))
        .map_err(|_| anyhow::anyhow!("submit_limit_buy: invalid token_id: {:?}", token_id))?;

    // PCS-2: adjust to the market's REAL tick BEFORE building the builder — the SDK
    // does not truncate (it aborts the build if price.scale() > tick.scale()).
    let price = price_at_market_tick(bundle, sdk_token_id, price, Side::Buy).await?;

    // Truncate to whole shares: whole × price(≤4dp) → ≤4dp USDC (maker_amount), within the
    // margin the tick allows — with tick 0.001 the SDK accepts up to 4dp of amount.
    let size_trunc = size.trunc_with_scale(0);
    if size_trunc <= Decimal::ZERO {
        anyhow::bail!(
            "submit_limit_buy: size after truncating to whole is 0 (price={price}, size={size})"
        );
    }

    let mut builder = bundle
        .client
        .limit_order()
        .token_id(sdk_token_id)
        .price(price)
        .size(size_trunc)
        .side(Side::Buy)
        .order_type(OrderType::GTD)
        .expiration(expiration);
    if post_only {
        builder = builder.post_only(true);
    }
    let signable = tokio::time::timeout(CLOB_HTTP_TIMEOUT, builder.build())
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "submit_limit_buy build: timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| {
            anyhow::anyhow!("submit_limit_buy build (price={price}, size={size_trunc}): {e}")
        })?;

    let signed = bundle
        .client
        .sign(bundle.signer.as_ref(), signable)
        .await
        .map_err(|e| anyhow::anyhow!("submit_limit_buy sign: {e}"))?;

    let resp = tokio::time::timeout(CLOB_HTTP_TIMEOUT, bundle.client.post_order(signed))
        .await
        .map_err(|_| {
            anyhow::anyhow!(
                "submit_limit_buy post_order: timeout ({}s)",
                CLOB_HTTP_TIMEOUT.as_secs()
            )
        })?
        .map_err(|e| anyhow::anyhow!("submit_limit_buy post_order: {e}"))?;

    // A GTD may partially cross on submission if a counterparty is available.
    // making_amount = USDC paid; taking_amount = shares received.
    let (executed_price, executed_size) =
        if resp.making_amount > Decimal::ZERO && resp.taking_amount > Decimal::ZERO {
            (
                Some(resp.making_amount / resp.taking_amount),
                Some(resp.taking_amount),
            )
        } else {
            (None, None)
        };

    Ok(SubmitResult {
        order_id: resp.order_id,
        executed_price,
        executed_size,
        success: resp.success,
        error: resp.error_msg,
        trade_ids: resp.trade_ids,
    })
}

