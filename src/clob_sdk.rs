    /// The retry wrapper recovers from a single transient failure…
    #[tokio::test]
    async fn retry_once_recovers_from_transient_failure() {
        let attempts = std::cell::Cell::new(0);
        let r = retry_once("op-test", || async {
            attempts.set(attempts.get() + 1);
            if attempts.get() == 1 {
                anyhow::bail!("transient")
            }
            Ok(42)
        })
        .await;
        assert_eq!(r.unwrap(), 42);
        assert_eq!(attempts.get(), 2);
    }

    /// …and after the second failure gives up with both errors in the message.
    #[tokio::test]
    async fn retry_once_gives_up_on_second_failure() {
        let attempts = std::cell::Cell::new(0);
        let r: anyhow::Result<i32> = retry_once("op-test", || async {
            attempts.set(attempts.get() + 1);
            anyhow::bail!("permanent")
        })
        .await;
        assert_eq!(attempts.get(), 2, "exactly 2 attempts, never more");
        let msg = r.unwrap_err().to_string();
        assert!(
            msg.contains("retry failed") && msg.contains("permanent"),
            "{msg}"
        );
    }

    /// map_buy_response is never exercised in paper (the sim creates Fills
    /// directly) — these real CLOB JSON fixtures cover the parsing
    /// that is only seen in live.
    fn parse(json: &str) -> PostOrderResponse {
        serde_json::from_str(json).expect("parseable CLOB JSON fixture")
    }

