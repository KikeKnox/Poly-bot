    fn snap_to_tick_clamps_to_lower_range() {
        assert_eq!(adjust_to_tick(dec!(0), dec!(0.01), Side::Buy), dec!(0.01));
        assert_eq!(
            adjust_to_tick(dec!(-1), dec!(0.001), Side::Buy),
            dec!(0.001)
        );
        // Positive price but smaller than the tick.
        assert_eq!(
            adjust_to_tick(dec!(0.005), dec!(0.01), Side::Buy),
            dec!(0.01)
        );
    }

