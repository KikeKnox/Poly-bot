/// Cancels an order on the CLOB by its `order_id`.
///
/// Used by `near_certain` in passive mode to cancel the pending limit order before
/// crossing to market FOK (fallback) or aborting the purchase due to reversal risk.
/// Returns the server result; the caller must log the `not_canceled` entries if any.
pub async fn cancel_order(
    bundle: &AuthedClobClient,
    order_id: &str,
) -> anyhow::Result<CancelOrdersResponse> {
    // Cancelling is idempotent (cancelling twice = cancelled) → safe retry.
    let resp = retry_once("cancel_order", move || async move {
        tokio::time::timeout(CLOB_CANCEL_TIMEOUT, bundle.client.cancel_order(order_id))
            .await
            .map_err(|_| {
                anyhow::anyhow!(
                    "cancel_order({order_id}): timeout ({}s)",
                    CLOB_CANCEL_TIMEOUT.as_secs()
                )
            })?
            .map_err(|e| anyhow::anyhow!("cancel_order({order_id}): {e}"))
    })
    .await?;

    // DELETE /order responds 200 OK even if it cancels nothing — the real
    // reason goes in `not_canceled` (order_id -> reason), not in the HTTP status. Without
    // this check, a CLOB rejection (rate limit, order mid-match,
    // etc.) was accounted for as a successful cancel.
    check_cancel_response(&resp, order_id)?;
    Ok(resp)
}

/// Pure so the fail-safe criterion can be tested without a network. "Benign" reasons
/// (the order no longer exists as such — it filled or expired) are accepted as if it
/// had been cancelled, because there is nothing left to cancel and it is safe for the
/// caller to clean up its entry. Any other (unrecognized) reason is treated
/// as `Err` by default — fail-safe.
fn check_cancel_response(resp: &CancelOrdersResponse, order_id: &str) -> anyhow::Result<()> {
    let Some(reason) = resp.not_canceled.get(order_id) else {
        return Ok(());
    };
    let reason_lower = reason.to_ascii_lowercase();
    let benign = reason_lower.contains("filled")
        || reason_lower.contains("expired")
        || reason_lower.contains("not found");
    if benign {
        tracing::info!(
            order_id,
            reason,
            "cancel_order: not_canceled with benign reason — treated as cancelled"
        );
        Ok(())
    } else {
        anyhow::bail!("cancel_order({order_id}): rejected by the CLOB (not_canceled): {reason}");
    }
}

